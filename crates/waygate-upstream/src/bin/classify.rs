    #[test]
    fn rendered_yaml_carries_header_and_round_trips_through_loader() {
        let manifest = starter_manifest(
            "example-observability",
            &Endpoint::Http("http://example-observability:8000/mcp".into()),
            vec![live("query_range"), live("list_dashboards")],
        );
        let yaml = render_manifest_yaml(&manifest).unwrap();
        assert!(yaml.starts_with("# Auto-generated by `classify`"));
        assert!(yaml.contains("REVIEW EACH ENTRY"));

        // Skip the comment block when deserializing; serde_yaml ignores leading
        // comments already, so this is just a belt-and-braces round-trip check.
        let reparsed: UpstreamManifest = serde_yaml::from_str(&yaml).unwrap();
        assert_eq!(reparsed.name, "example-observability");
        let names: Vec<&str> = reparsed.tools.iter().map(|t| t.name.as_str()).collect();
        assert_eq!(names, vec!["list_dashboards", "query_range"]);
        assert_eq!(reparsed.tools[0].risk, RiskTier::Low);
    }

