//! every `ToSchema`-deriving DTO into a single `utoipa::OpenApi` value. The
//! spec is served at `/api/v1/openapi.json` by [`router`] — deliberately
//! *outside* the scope-gated sub-routers so tooling (Swagger UI, client
//! codegen, CI lint) can fetch it without a bearer token. The spec only
//! describes shapes, not secrets; callers still need `mcp:read` / `mcp:admin`
//! to actually hit the documented endpoints.

