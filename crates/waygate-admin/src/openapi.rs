/// Build a router that serves the OpenAPI 3.1 JSON spec at
/// `/api/v1/openapi.json`. Intentionally unauthenticated — see module docs.
pub fn router() -> Router<()> {
    Router::new().route("/api/v1/openapi.json", get(spec_json))
}

async fn spec_json() -> Json<utoipa::openapi::OpenApi> {
    Json(ApiDoc::openapi())
}
